// Before this file existed, every position's JobPosting JSON-LD reused the
// same site-wide POSITION_REVIEW_LABEL date (lib/positionFreshness.js) for
// `datePosted` — so Google Jobs saw ~180 different postings all claiming to
// have gone live on the same single day, and that day only changed when
// someone next edited the label. That's a real freshness-signal miss: Google
// Jobs ranks partly on how recently a posting was actually posted, and it
// can't tell genuinely new roles apart from old ones when they all carry an
// identical, manually-managed date.
//
// These dates were reconstructed once, from git history, as the date each
// Position ID's record first entered this repo (`git log --diff-filter=A
// --reverse -S'"id":"<id>"' -- data/jobs/`, earliest match). For positions
// bulk-imported when this site was first built (2026-08-07), that's the date
// the listing went live on agileconsultingsolutions.com — not necessarily
// the role's original opening date at the client, which predates this site
// and isn't tracked anywhere in this repo. That's why a large cluster of
// early IDs legitimately share 2026-08-07: they were migrated in together.
// Everything added since (1173+) already has its own accurate, incremental
// date because each was a separate commit.
//
// Maintenance: whenever a new Position ID is added to data/jobs/*.js, add a
// matching "<id>": "YYYY-MM-DD" entry here with the real date it went live.
// app/careers/positions/[slug]/page.js falls back to the site-wide
// POSITION_REVIEW_LABEL date for any Position ID not listed here, so nothing
// breaks if this is missed — but the new posting won't get an accurate
